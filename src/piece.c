int piece_cell(PieceType type, int rotation, int row, int col) {
    return shapes[type][rotation][row][col];
}

Piece piece_spawn(void) {
    Piece p;
    p.type     = (PieceType)(rand() % PIECE_COUNT);
    p.rotation = 0;
    p.x        = 3;
    p.y        = 0;
    return p;
}

Piece piece_rotated(Piece p, int dir) {
    p.rotation = (p.rotation + dir + 4) % 4;
    return p;
}
